    assert len(values) == len(KEYS), (lang, len(values))
    msgs = {"extName": {"message": "YT Music Comments"}}
    for key, value in zip(KEYS, values):
        entry = {"message": value.replace("$1", "$COUNT$")} if "$1" in value else {"message": value}
